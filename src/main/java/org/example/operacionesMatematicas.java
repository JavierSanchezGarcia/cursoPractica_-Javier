package org.example;

public class operacionesMatematicas {
    public static String operacionSuma(int num1, int num2) {
        //int resultadoDeSuma = num1 + num2;
        return "El resultado de la suma de dos numeros es: " + (num1 + num2); //cadena + el valor de la suma
    }

    public static String operacionResta(int num1, int num2) {
        //int resultadoDeResta = num1 + num2;
        return "El resultado de la resta de dos numeros es: " + (num1 - num2); //cadena + el valor de la resta
    }

    public static String operacionMultiplicacion(int num1, int num2) {
        //int resultadoDeMultiplicacion = num1 + num2;
        return "El resultado de la Multiplicacion de dos numeros es: " + (num1 * num2); //cadena + el valor de la Multiplicacion
    }

    public static String operacionDivicion(int num1, int num2) {
        //int resultadoDeDivicion = num1 + num2;
        return "El resultado de la Divicion de dos numeros es: " + (num1 / num2); //cadena + el valor de la Divicion
    }
}




